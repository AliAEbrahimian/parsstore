def current_language() -> str:
    code = translation.get_language() or DEFAULT_LANGUAGE
    code = code.split("-")[0]
    return code if code in dict(LANGUAGES) else DEFAULT_LANGUAGE


def t(key: str, lang: str | None = None) -> str:
    """Return the translation for a key in the active (or explicit) language."""
    entry = UI.get(key)
    if entry is None:
        return key
    code = (lang or current_language()).split("-")[0]
    return entry.get(code) or entry[DEFAULT_LANGUAGE]


def flat(lang: str | None = None) -> dict[str, str]:
    """Return all strings as a flat dict for use in templates."""
    code = (lang or current_language()).split("-")[0]
    return {key: value.get(code) or value[DEFAULT_LANGUAGE] for key, value in UI.items()}
